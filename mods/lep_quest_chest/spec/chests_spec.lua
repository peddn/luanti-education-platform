local chests = dofile("mods/lep_quest_chest/src/chests.lua")

local A = { x = 10, y = 5, z = -3 }
local B = { x = 200, y = 8, z = 40 }

describe("lep_quest_chest store", function()
	it("adds and removes chests by position", function()
		local store = chests.new_store()
		assert.is_false(store:has(A))
		assert.is_true(store:add(A, 100))
		assert.is_true(store:has(A))
		assert.is_false(store:add(A, 200))
		assert.are.same({ A }, store:positions())
		assert.is_true(store:remove(A))
		assert.is_false(store:remove(A))
		assert.is_false(store:has(A))
	end)

	it("does not keep the position table it was given", function()
		local store = chests.new_store()
		local pos = { x = 1, y = 2, z = 3 }
		store:add(pos, 100)
		pos.x = 99
		assert.is_true(store:has({ x = 1, y = 2, z = 3 }))
	end)

	it("lets every player solve a chest once", function()
		local store = chests.new_store()
		store:add(A, 100)
		assert.is_false(store:has_solved(A, "anna"))
		assert.is_true(store:mark_solved(A, "anna", 150))
		assert.is_true(store:has_solved(A, "anna"))
		assert.is_false(store:mark_solved(A, "anna", 160))
		assert.is_false(store:has_solved(A, "ben"))
		assert.is_true(store:mark_solved(A, "ben", 170))
		assert.is_false(store:mark_solved(B, "anna", 150))
	end)

	it("removes an unsolved chest after 30 minutes", function()
		local store = chests.new_store()
		store:add(A, 1000)
		assert.are.equal(1000 + 1800, store:expires_at(A))
		assert.are.same({}, store:expired(1000 + 1799))
		assert.are.same({ A }, store:expired(1000 + 1800))
	end)

	it("removes a chest 10 minutes after it was solved first", function()
		local store = chests.new_store()
		store:add(A, 1000)
		store:mark_solved(A, "anna", 1100)
		store:mark_solved(A, "ben", 1500)
		assert.are.equal(1100 + 600, store:expires_at(A))
		assert.are.same({}, store:expired(1699))
		assert.are.same({ A }, store:expired(1700))
	end)

	it("never lets a chest stay longer because it was solved", function()
		local store = chests.new_store()
		store:add(A, 1000)
		store:mark_solved(A, "anna", 1000 + 1700)
		assert.are.equal(1000 + 1800, store:expires_at(A))
	end)

	it("keeps the chests of teachers", function()
		local store = chests.new_store()
		store:add(A, 1000, true)
		store:mark_solved(A, "anna", 1100)
		assert.is_true(store:is_permanent(A))
		assert.is_nil(store:expires_at(A))
		assert.are.same({}, store:expired(1000000))
	end)

	it("limits the spawned chests, not those of teachers", function()
		local store = chests.new_store()
		for index = 1, chests.MAX_SPAWNED - 1 do
			store:add({ x = index * 100, y = 0, z = 0 }, 100)
		end
		store:add({ x = 0, y = 50, z = 0 }, 100, true)
		store:add({ x = 0, y = 60, z = 0 }, 100, true)
		assert.are.equal(chests.MAX_SPAWNED - 1, store:count_spawned())
		assert.is_true(store:can_spawn())
		store:add({ x = 0, y = 0, z = 100 }, 100)
		assert.is_false(store:can_spawn())
	end)

	it("knows whether a chest is nearby", function()
		local store = chests.new_store()
		store:add(A, 100)
		assert.is_true(store:has_nearby({ x = 10 + 80, y = 90, z = -3 }, "anna"))
		assert.is_false(store:has_nearby({ x = 10 + 81, y = 5, z = -3 }, "anna"))
		assert.is_false(store:has_nearby(B, "anna"))
	end)

	it("counts a solved spawned chest as nearby, a solved teacher chest not", function()
		local store = chests.new_store()
		store:add(A, 100)
		store:add(B, 100, true)
		store:mark_solved(A, "anna", 150)
		store:mark_solved(B, "anna", 150)
		assert.is_true(store:has_nearby(A, "anna"))
		assert.is_false(store:has_nearby(B, "anna"))
		assert.is_true(store:has_nearby(B, "ben"))
	end)

	it("can make spawned chests older", function()
		local store = chests.new_store()
		store:add(A, 1000)
		store:add(B, 1000, true)
		store:mark_solved(A, "anna", 1100)
		store:age(540)
		assert.are.same({}, store:expired(1100 + 59))
		assert.are.same({ A }, store:expired(1100 + 60))
		assert.is_true(store:has_solved(A, "anna"))
	end)

	it("survives saving and loading", function()
		local store = chests.new_store()
		store:add(A, 100)
		store:add(B, 200, true)
		store:mark_solved(A, "anna", 150)
		local copy = chests.new_store(store:data())
		assert.are.same(store:data(), copy:data())
		assert.is_true(copy:has_solved(A, "anna"))
		assert.is_true(copy:is_permanent(B))
		assert.are.equal(150 + 600, copy:expires_at(A))
	end)

	it("drops stored entries it cannot read", function()
		local store = chests.new_store({
			"text",
			{ pos = { x = 1, y = 2 }, created = 5 },
			{ pos = A },
			{ pos = B, created = 7, solved = "nobody", first_solved = "never" },
		})
		assert.are.same({ B }, store:positions())
		assert.are.equal(7 + 1800, store:expires_at(B))
		assert.are.same({}, chests.new_store("broken"):positions())
	end)
end)

describe("lep_quest_chest attempts", function()
	it("keeps the task of a player at a chest", function()
		local attempts = chests.new_attempts()
		assert.is_nil(attempts:get_task("anna", A))
		local task = { text = "1 + 1 = ?" }
		attempts:set_task("anna", A, task)
		assert.are.equal(task, attempts:get_task("anna", A))
		assert.is_nil(attempts:get_task("ben", A))
		assert.is_nil(attempts:get_task("anna", B))
		assert.are.equal(0, attempts:wait_left("anna", A, 100))
	end)

	it("takes the task away and makes the player wait after a wrong answer", function()
		local attempts = chests.new_attempts()
		attempts:set_task("anna", A, { text = "1 + 1 = ?" })
		assert.are.equal(1, attempts:fail("anna", A, 100))
		assert.is_nil(attempts:get_task("anna", A))
		assert.are.equal(30, attempts:wait_left("anna", A, 100))
		assert.are.equal(1, attempts:wait_left("anna", A, 129))
		assert.are.equal(0, attempts:wait_left("anna", A, 130))
		assert.are.equal(0, attempts:wait_left("anna", A, 500))
		assert.are.equal(0, attempts:wait_left("anna", B, 100))
		assert.are.equal(0, attempts:wait_left("ben", A, 100))
	end)

	it("counts the wrong answers", function()
		local attempts = chests.new_attempts()
		assert.are.equal(0, attempts:tries("anna", A))
		attempts:fail("anna", A, 100)
		assert.are.equal(2, attempts:fail("anna", A, 200))
		assert.are.equal(2, attempts:tries("anna", A))
	end)

	it("forgets a chest for all players", function()
		local attempts = chests.new_attempts()
		attempts:set_task("anna", A, {})
		attempts:fail("ben", A, 100)
		attempts:set_task("anna", B, {})
		attempts:forget_chest(A)
		assert.is_nil(attempts:get_task("anna", A))
		assert.are.equal(0, attempts:wait_left("ben", A, 100))
		assert.is_not_nil(attempts:get_task("anna", B))
	end)
end)

describe("lep_quest_chest spawning", function()
	it("checks the distance to a chest", function()
		assert.is_true(chests.in_reach({ x = 10, y = 5, z = 3 }, A))
		assert.is_false(chests.in_reach({ x = 10, y = 5, z = 4 }, A))
		assert.is_false(chests.in_reach(B, A))
	end)

	it("spawns between 30 and 80 nodes away, in all directions", function()
		local seed = 7
		local function random(min, max)
			seed = (seed * 1103515245 + 12345) % 2147483648
			return min + math.floor(seed / 65536) % (max - min + 1)
		end
		local quadrants = {}
		for _ = 1, 500 do
			local dx, dz = chests.spawn_offset(random)
			local distance = math.sqrt(dx * dx + dz * dz)
			assert.is_true(distance >= chests.SPAWN_MIN - 1 and distance <= chests.SPAWN_MAX + 1)
			quadrants[(dx >= 0 and "e" or "w") .. (dz >= 0 and "n" or "s")] = true
		end
		assert.is_true(quadrants.en and quadrants.es and quadrants.wn and quadrants.ws)
	end)

	it("names the direction of an offset", function()
		assert.are.equal("n", chests.direction(0, 50))
		assert.are.equal("s", chests.direction(0, -50))
		assert.are.equal("e", chests.direction(50, 0))
		assert.are.equal("w", chests.direction(-50, 0))
		assert.are.equal("ne", chests.direction(40, 40))
		assert.are.equal("nw", chests.direction(-40, 40))
		assert.are.equal("se", chests.direction(40, -40))
		assert.are.equal("sw", chests.direction(-40, -40))
		assert.are.equal("n", chests.direction(10, 50))
		assert.are.equal("w", chests.direction(-50, -10))
	end)

	it("accepts natural solid ground only", function()
		assert.is_true(chests.is_ground({ groups = { soil = 1, crumbly = 3 } }))
		assert.is_true(chests.is_ground({ groups = { sand = 1 } }))
		assert.is_true(chests.is_ground({ groups = { stone = 1 } }))
		assert.is_true(chests.is_ground({ groups = { snowy = 1 } }))
		assert.is_false(chests.is_ground({ groups = { leaves = 1 } }))
		assert.is_false(chests.is_ground({ groups = { wood = 1 } }))
		assert.is_false(chests.is_ground({ groups = {} }))
		assert.is_false(chests.is_ground({ walkable = false, groups = { soil = 1 } }))
		assert.is_false(chests.is_ground({ liquidtype = "source", groups = { sand = 1 } }))
		assert.is_true(chests.is_ground({ liquidtype = "none", groups = { sand = 1 } }))
		assert.is_false(chests.is_ground(nil))
	end)

	it("recognises trees", function()
		assert.is_true(chests.is_tree({ groups = { leaves = 1, snappy = 3 } }))
		assert.is_true(chests.is_tree({ groups = { tree = 1, choppy = 2 } }))
		assert.is_false(chests.is_tree({ groups = { wood = 1 } }))
		assert.is_false(chests.is_tree({ groups = { soil = 1 } }))
		assert.is_false(chests.is_tree({}))
		assert.is_false(chests.is_tree(nil))
	end)
end)
