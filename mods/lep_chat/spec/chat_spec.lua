local chat = dofile("mods/lep_chat/src/chat.lua")

describe("lep_chat private messages", function()
	it("splits recipient and message", function()
		local recipient, message = chat.parse_private("anna hello there")
		assert.are.equal("anna", recipient)
		assert.are.equal("hello there", message)
	end)

	it("rejects what the engine rejects", function()
		assert.is_nil(chat.parse_private("anna"))
		assert.is_nil(chat.parse_private(""))
		assert.is_nil(chat.parse_private(" hello"))
		assert.is_nil(chat.parse_private(nil))
	end)
end)

describe("lep_chat mutes", function()
	it("mutes players who can speak", function()
		local mutes = chat.new_mutes()
		assert.is_false(mutes:is_muted("anna"))
		assert.is_true(mutes:mute("anna", true))
		assert.is_true(mutes:is_muted("anna"))
		assert.is_false(mutes:mute("anna", true))
	end)

	it("leaves out players who cannot speak anyway", function()
		local mutes = chat.new_mutes()
		assert.is_false(mutes:mute("ben", false))
		assert.is_false(mutes:is_muted("ben"))
		assert.is_false(mutes:unmute("ben"))
	end)

	it("lifts a mute once", function()
		local mutes = chat.new_mutes()
		mutes:mute("anna", true)
		assert.is_true(mutes:unmute("anna"))
		assert.is_false(mutes:unmute("anna"))
		assert.is_false(mutes:is_muted("anna"))
	end)

	it("lifts all mutes at once", function()
		local mutes = chat.new_mutes()
		mutes:mute("mia", true)
		mutes:mute("anna", true)
		assert.are.same({ "anna", "mia" }, mutes:unmute_all())
		assert.are.same({}, mutes:data())
		assert.are.same({}, mutes:unmute_all())
	end)

	it("survives saving and loading", function()
		local mutes = chat.new_mutes()
		mutes:mute("mia", true)
		mutes:mute("anna", true)
		local copy = chat.new_mutes(mutes:data())
		assert.are.same({ "anna", "mia" }, copy:data())
		assert.is_true(copy:is_muted("mia"))
	end)

	it("drops stored data it cannot read", function()
		assert.are.same({ "anna" }, chat.new_mutes({ "anna", 5, "", {} }):data())
		assert.are.same({}, chat.new_mutes("broken"):data())
	end)
end)
