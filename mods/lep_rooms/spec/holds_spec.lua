local holds = dofile("mods/lep_rooms/src/holds.lua")

describe("lep_rooms holds", function()
	it("holds and releases players", function()
		local list = holds.new()
		assert.is_false(list:is_held("anna"))
		assert.is_true(list:hold("anna"))
		assert.is_false(list:hold("anna"))
		assert.is_true(list:is_held("anna"))
		assert.is_false(list:is_held("ben"))
		assert.is_true(list:release("anna"))
		assert.is_false(list:release("anna"))
		assert.is_false(list:is_held("anna"))
	end)

	it("releases everybody at once", function()
		local list = holds.new()
		list:hold("mia")
		list:hold("anna")
		assert.are.same({ "anna", "mia" }, list:release_all())
		assert.is_false(list:is_held("anna"))
		assert.are.same({}, list:release_all())
	end)

	it("rejects names that are none", function()
		local list = holds.new()
		assert.has_error(function() list:hold("") end)
		assert.has_error(function() list:hold(nil) end)
	end)
end)
